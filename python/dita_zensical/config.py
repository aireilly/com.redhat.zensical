# Content-address the output filename so browsers fetch a changed stylesheet
# without tying the asset name to the plug-in release number.
CSS_SOURCE = Path(__file__).resolve().parents[2] / "resources" / "dita.css"
CSS_FINGERPRINT = hashlib.sha256(CSS_SOURCE.read_bytes()).hexdigest()[:12]
CSS_FILENAME = "dita.{}.css".format(CSS_FINGERPRINT)
CSS_ENTRY = 'extra_css = ["stylesheets/{}"]'.format(CSS_FILENAME)

# Folder, relative to zensical.toml, that holds the page-action partial for source links
OVERRIDES_DIR = "overrides"


def action_features(actions) -> list[str]:
    return ["content.action." + action for action in actions]


def q(value: str) -> str:
    """TOML basic string (JSON string syntax is a subset)."""
    return json.dumps(value, ensure_ascii=False)


def theme_icon(text: str, name: str, default: str) -> str:
    """Read a configured theme icon name, or use the theme's default icon."""
    if tomllib is None:
        return default
    try:
        data = tomllib.loads(text)
    except tomllib.TOMLDecodeError:
        return default
    icon = data.get("project", {}).get("theme", {}).get("icon", {}).get(name, default)
    return icon if isinstance(icon, str) else default


def nav_toml(nav, with_home: bool) -> str:
    entries = ([q("index.md")] if with_home else []) + [e for item in nav for e in _entries(item)]
    return "\n".join(["nav = ["] + ["  {},".format(e) for e in entries] + ["]"])


def _entries(item) -> list[str]:
    children = [e for child in item.children for e in _entries(child)]
    target = q(markdown_path(item.page)) if item.page else (q(item.url) if item.url else None)
    title = q(item.title) if item.title else None
    if target is None:
        if not children:
            return []
        return ["{{ {} = [ {} ] }}".format(title, ", ".join(children))] if title else children
    if not children:
        return ["{{ {} = {} }}".format(title, target)] if title else [target]
    if title:
        return ["{{ {} = [ {} ] }}".format(title, ", ".join([target] + children))]
    return [target] + children


def default_config(site_name, nav_block, *, description="", url="", repo_url="", language="en",
                   source_actions=()) -> str:
    lines = [HEADER, "[project]", "site_name = " + q(site_name)]
    if description:
        lines.append("site_description = " + q(description))
    if url:
        lines.append("site_url = " + q(url))
    if repo_url:
        lines.append("repo_url = " + q(repo_url))
    lines += ['docs_dir = "docs"', 'site_dir = "site"', CSS_ENTRY, nav_block, "",
              THEME_AND_EXTENSIONS.format(
                  language=q(language),
                  custom_dir="\ncustom_dir = " + q(OVERRIDES_DIR) if source_actions else "",
                  action_features="".join("\n  " + q(f) + "," for f in action_features(source_actions)))]
    return "\n".join(lines)


def merge_user_config(text: str, site_name: str, nav_block: str) -> str:
    """Add site_name, extra_css and nav under [project] when the user's file lacks them."""
    inject = []
    if not re.search(r"^[ \t]*site_name[ \t]*=", text, re.M):
        inject.append("site_name = " + q(site_name))
    if not re.search(r"^[ \t]*extra_css[ \t]*=", text, re.M):
        inject.append(CSS_ENTRY)
    if not re.search(r"^[ \t]*nav[ \t]*=", text, re.M):
        inject.append(nav_block)
    if not inject:
        return text
    block = "\n".join(inject)
    project = re.search(r"^[ \t]*\[project\][ \t]*\r?$", text, re.M)
    if project:
        return text[:project.end()] + "\n" + block + text[project.end():]
    return "[project]\n" + block + "\n\n" + text


def ensure_source_actions(text: str, actions) -> tuple[str, str, list[str]]:
    """Make a user's zensical.toml render source links with Zensical's page-action buttons.

    Adds custom_dir and the content.action.* features under [project.theme] when
    missing. Returns the new text, the custom_dir in effect, and warnings.
    """
    warnings = []
    theme = {}
    if tomllib is not None:
        try:
            theme = tomllib.loads(text).get("project", {}).get("theme", {})
        except tomllib.TOMLDecodeError as exc:
            return text, OVERRIDES_DIR, ["cannot read zensical.config to add source-link settings: {}".format(exc)]
    wanted = action_features(actions)
    custom_dir = theme.get("custom_dir")
    header = re.search(r"^[ \t]*\[project\.theme\][ \t]*\r?$", text, re.M)

    if header is None:
        lines = ["", "[project.theme]", "custom_dir = " + q(OVERRIDES_DIR),
                 "features = [" + ", ".join(q(f) for f in wanted) + "]"]
        return text.rstrip("\n") + "\n" + "\n".join(lines) + "\n", OVERRIDES_DIR, warnings

    insert = []
    if custom_dir is None:
        insert.append("custom_dir = " + q(OVERRIDES_DIR))
        custom_dir = OVERRIDES_DIR
    features = theme.get("features")
    if features is None:
        insert.append("features = [" + ", ".join(q(f) for f in wanted) + "]")
    else:
        missing = [f for f in wanted if f not in features]
        if missing:
            array = re.compile(r"^([ \t]*features[ \t]*=[ \t]*\[)", re.M).search(text, header.end())
            if array:
                added = "".join(" " + q(f) + "," for f in missing)
                text = text[:array.end()] + added + text[array.end():]
            else:
                warnings.append("add {} to [project.theme] features in zensical.config".format(", ".join(missing)))
    if insert:
        text = text[:header.end()] + "\n" + "\n".join(insert) + text[header.end():]
    return text, str(custom_dir), warnings
